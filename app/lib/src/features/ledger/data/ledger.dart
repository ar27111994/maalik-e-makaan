/// Money received for a tenancy (LEDGER-03), with its receipt number
/// (LEDGER-05), the tax the tenant withheld (LEDGER-10) and the dues it
/// settled.
@immutable
final class Payment {
  const new({
    required this.id,
    required this.leaseId,
    required this.amount,
    required this.paidOn,
    required this.method,
    required this.receiptNumber,
    this.taxWithheld = Money.zero,
    this.allocatedAmount = Money.zero,
    this.reference,
    this.taxCertificateNo,
    this.notes,
    this.voidedAt,
    this.voidReason,
    this.createdAt = '',
    this.allocations = const [],
  });

  /// Reads a `payments` row selected with [Payment.columns], or the
  /// `payment` of a `record_payment` answer with [allocations] given.
  factory fromRow(Object? json, {List<Allocation>? allocations}) {
    final row = JsonRow.of(json, 'payment');
    return Payment(
      id: row.string('id'),
      leaseId: row.string('lease_id'),
      amount: row.money('amount'),
      taxWithheld: row.money('tax_withheld'),
      allocatedAmount: row.money('allocated_amount'),
      paidOn: row.date('paid_on'),
      method: row.choice('method', PaymentMethod.parse),
      reference: row.optionalString('reference'),
      taxCertificateNo: row.optionalString('tax_certificate_no'),
      notes: row.optionalString('notes'),
      receiptNumber: row.string('receipt_number'),
      voidedAt: row.optionalTimestamp('voided_at'),
      voidReason: row.optionalString('void_reason'),
      createdAt: row.string('created_at'),
      allocations:
          allocations ??
          [for (final a in row.list('allocations')) Allocation.fromRow(a)],
    );
  }

  static const columns =
      'id,lease_id,amount,tax_withheld,allocated_amount,paid_on,method,'
      'reference,tax_certificate_no,notes,receipt_number,voided_at,'
      'void_reason,created_at,'
      'allocations:payment_allocations!payment_allocations_payment_fkey'
      '(charge_id,amount)';

  static const maxReferenceLength = 80;
  static const maxCertificateLength = 60;
  static const maxNotesLength = 500;
  static const maxReasonLength = 300;

  final String id;
  final String leaseId;

  /// The cash (or transfer) received.
  final Money amount;

  /// Income tax the tenant deducted under s.155; with [amount] it settles
  /// the gross due.
  final Money taxWithheld;
  final Money allocatedAmount;
  final CalendarDate paidOn;
  final PaymentMethod method;
  final String? reference;
  final String? taxCertificateNo;
  final String? notes;
  final String receiptNumber;
  final DateTime? voidedAt;
  final String? voidReason;
  final String createdAt;

  /// The dues it settled and how much of each.
  final List<Allocation> allocations;

  bool get voided => voidedAt != null;

  /// What it settles: the cash and the tax withheld.
  Money get applied => amount + taxWithheld;

  /// What no due has taken yet: the tenant's credit.
  Money get unallocated => voided ? Money.zero : applied - allocatedAmount;

  PageCursor get cursor => PageCursor(createdAt: createdAt, id: id);

  Map<String, Object?> toRow() => {
    'id': id,
    'lease_id': leaseId,
    'amount': amount.toJson(),
    'tax_withheld': taxWithheld.toJson(),
    'allocated_amount': allocatedAmount.toJson(),
    'paid_on': paidOn.toJson(),
    'method': method.db,
    'reference': reference,
    'tax_certificate_no': taxCertificateNo,
    'notes': notes,
    'receipt_number': receiptNumber,
    'voided_at': voidedAt?.toIso8601String(),
    'void_reason': voidReason,
    'created_at': createdAt,
    'allocations': [for (final a in allocations) a.toRow()],
  };

  @override
  bool operator ==(Object other) =>
      other is Payment && mapEquals(_comparable(other), _comparable(this));

  static Map<String, Object?> _comparable(Payment p) =>
      p.toRow()..['allocations'] = Object.hashAll(p.allocations);

  @override
  int get hashCode => Object.hashAll(_comparable(this).values);
}

/// What a payment to be recorded says (`record_payment`'s arguments).
@immutable
final class PaymentDraft {
  const new({
    required this.leaseId,
    required this.amount,
    required this.paidOn,
    required this.method,
    required this.idempotencyKey,
    this.taxWithheld = Money.zero,
    this.taxCertificateNo,
    this.reference,
    this.notes,
    this.chargeIds,
  });

  final String leaseId;
  final Money amount;
  final CalendarDate paidOn;
  final PaymentMethod method;

  /// Made once when the form opens and kept for every retry, so a retried
  /// request records the payment only once.
  final String idempotencyKey;
  final Money taxWithheld;
  final String? taxCertificateNo;
  final String? reference;
  final String? notes;

  /// The dues to settle first, in order; null settles the oldest first.
  final List<String>? chargeIds;

  Map<String, Object?> toParams() => {
    'p_lease_id': leaseId,
    'p_amount': amount.toJson(),
    'p_paid_on': paidOn.toJson(),
    'p_method': method.db,
    'p_idempotency_key': idempotencyKey,
    'p_reference': sanitizeOptional(
      reference,
      maxLength: Payment.maxReferenceLength,
    ),
    'p_notes': _multiline(notes, Payment.maxNotesLength),
    'p_tax_withheld': taxWithheld.toJson(),
    'p_tax_certificate_no': sanitizeOptional(
      taxCertificateNo,
      maxLength: Payment.maxCertificateLength,
    ),
    'p_charge_ids': chargeIds,
  };

  @override
  bool operator ==(Object other) =>
      other is PaymentDraft && mapEquals(other.toParams(), toParams());

  @override
  int get hashCode => Object.hashAll(toParams().values);
}

String? _multiline(String? value, int max) {
  if (value == null) return null;
  final clean = sanitizeMultiline(value, maxLength: max);
  return clean.isEmpty ? null : clean;
}

/// A recorded payment as `record_payment` and `apply_deposit` answer: the
/// payment, the dues it settled, and what the tenancy owes and holds as
/// credit after it.
@immutable
final class PaymentResult {
  const new({
    required this.payment,
    required this.settled,
    required this.leaseOutstanding,
    required this.leaseCredit,
  });

  factory fromJson(Object? json) {
    final row = JsonRow.of(json, 'payment result');
    final settled = [
      for (final a in row.list('allocations')) SettledCharge.fromResult(a),
    ];
    return PaymentResult(
      payment: Payment.fromRow(
        row.object('payment'),
        allocations: [
          for (final s in settled)
            Allocation(chargeId: s.chargeId, amount: s.amount),
        ],
      ),
      settled: settled,
      leaseOutstanding: row.money('lease_outstanding'),
      leaseCredit: row.money('lease_credit'),
    );
  }

  final Payment payment;
  final List<SettledCharge> settled;
  final Money leaseOutstanding;
  final Money leaseCredit;
}

