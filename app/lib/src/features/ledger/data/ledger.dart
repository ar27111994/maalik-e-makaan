    final phone = row.optionalString('tenant_phone');
    return Receivable(
      leaseId: row.string('lease_id'),
      active:
          row.choice('lease_status', LeaseStatus.parse) == LeaseStatus.active,
      tenantId: row.string('tenant_id'),
      tenantName: row.string('tenant_name'),
      tenantPhone: phone == null ? null : PhoneNumber.fromE164(phone),
      unitId: row.string('unit_id'),
      unitLabel: row.string('unit_label'),
      propertyId: row.string('property_id'),
      propertyName: row.string('property_name'),
      monthlyRent: row.money('monthly_rent'),
      balance: LeaseBalance.fromRow(row.toMap()),
    );
  }

  final String leaseId;
  final bool active;
  final String tenantId;
  final String tenantName;
  final PhoneNumber? tenantPhone;
  final String unitId;
  final String unitLabel;
  final String propertyId;
  final String propertyName;
  final Money monthlyRent;
  final LeaseBalance balance;

  Map<String, Object?> toRow() => {
    'lease_id': leaseId,
    'lease_status': (active ? LeaseStatus.active : LeaseStatus.ended).db,
    'tenant_id': tenantId,
    'tenant_name': tenantName,
    'tenant_phone': tenantPhone?.e164,
    'unit_id': unitId,
    'unit_label': unitLabel,
    'property_id': propertyId,
    'property_name': propertyName,
    'monthly_rent': monthlyRent.toJson(),
    ...balance.toRow(),
  };

  @override
  bool operator ==(Object other) =>
      other is Receivable && mapEquals(other.toRow(), toRow());

  @override
  int get hashCode => Object.hashAll(toRow().values);
}

/// A tenancy's money, as its ledger screen shows it: what it owes and
/// holds, every open due, the latest dues and payments (a page at a time,
/// newest first), its deposit and the refunds of it.
@immutable
final class TenancyLedger {
  const new({
    required this.lease,
    required this.balance,
    required this.openCharges,
    required this.charges,
    required this.payments,
    required this.deposit,
    required this.refunds,
  });

  factory fromJson(Object? json) {
    final row = JsonRow.of(json, 'ledger');
    return TenancyLedger(
      lease: Lease.fromRow(row.object('lease').toMap()),
      balance: LeaseBalance.fromRow(row.object('balance').toMap()),
      openCharges: [for (final c in row.list('open')) Charge.fromRow(c)],
      charges: Paged.fromJson(row.object('charges').toMap(), Charge.fromRow),
      payments: Paged.fromJson(row.object('payments').toMap(), Payment.fromRow),
      deposit: DepositPosition.fromJson(row.object('deposit').toMap()),
      refunds: [for (final r in row.list('refunds')) DepositRefund.fromRow(r)],
    );
  }

  final Lease lease;
  final LeaseBalance balance;

  /// Every due still owed, oldest first.
  final List<Charge> openCharges;

  /// Dues of every state, newest first.
  final Paged<Charge> charges;

  /// Payments, newest first.
  final Paged<Payment> payments;
  final DepositPosition deposit;

  /// Newest first.
  final List<DepositRefund> refunds;

  TenancyLedger copyWith({Paged<Charge>? charges, Paged<Payment>? payments}) =>
      TenancyLedger(
        lease: lease,
        balance: balance,
        openCharges: openCharges,
        charges: charges ?? this.charges,
        payments: payments ?? this.payments,
        deposit: deposit,
        refunds: refunds,
      );

  Map<String, Object?> toJson() => {
    'lease': lease.toRow(),
    'balance': balance.toRow(),
    'open': [for (final c in openCharges) c.toRow()],
    'charges': charges.toJson((c) => c.toRow()),
    'payments': payments.toJson((p) => p.toRow()),
    'deposit': deposit.toJson(),
    'refunds': [for (final r in refunds) r.toRow()],
  };

  @override
  bool operator ==(Object other) =>
      other is TenancyLedger &&
      other.lease == lease &&
      other.balance == balance &&
      listEquals(other.openCharges, openCharges) &&
      other.charges == charges &&
      other.payments == payments &&
      other.deposit == deposit &&
      listEquals(other.refunds, refunds);

  @override
  int get hashCode => Object.hash(
    lease,
    balance,
    Object.hashAll(openCharges),
    charges,
    payments,
    deposit,
    Object.hashAll(refunds),
  );
}

/// Everything a tenant statement (LEDGER-09) lists: every due and payment
/// of the tenancy, oldest first, and its deposit.
@immutable
final class LedgerStatement {
  const new({
    required this.lease,
    required this.charges,
    required this.payments,
    required this.deposit,
    required this.refunds,
  });

  final Lease lease;
  final List<Charge> charges;
  final List<Payment> payments;
  final DepositPosition deposit;
  final List<DepositRefund> refunds;

  /// What is owed now: the open dues' outstanding amounts.
  Money get outstanding => Money.sum([
    for (final c in charges)
      if (!c.voided) c.outstanding,
  ]);

  /// Money received that no due has taken.
  Money get credit => Money.sum([for (final p in payments) p.unallocated]);
}

/// The fields of a charge added by hand (`charges` insert grant: id,
/// portfolio_id, lease_id, kind, period_month, due_date, amount,
/// description).
@immutable
final class ChargeDraft {
  const new({
    required this.kind,
    required this.amount,
    required this.dueDate,
    this.periodMonth,
    this.description,
  });

  final ChargeKind kind;
  final Money amount;
  final CalendarDate dueDate;
  final MonthPeriod? periodMonth;
  final String? description;

  Map<String, Object?> toWrite() => {
    'kind': kind.db,
    'amount': amount.toJson(),
    'due_date': dueDate.toJson(),
    'period_month': periodMonth?.first.toJson(),
    'description': sanitizeOptional(
      description,
      maxLength: Charge.maxDescriptionLength,
    ),
  };

  @override
  bool operator ==(Object other) =>
      other is ChargeDraft && mapEquals(other.toWrite(), toWrite());

  @override
  int get hashCode => Object.hashAll(toWrite().values);
}

