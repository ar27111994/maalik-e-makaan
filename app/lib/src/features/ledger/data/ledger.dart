/// One payment with its tenancy and the dues it settled: what a receipt
/// shows.
@immutable
final class PaymentDetail {
  const new({
    required this.payment,
    required this.lease,
    required this.settled,
  });

  /// Reads a `payments` row selected with [PaymentDetail.columns].
  factory fromRow(Object? json) {
    final row = JsonRow.of(json, 'payment');
    final settled = [
      for (final a in row.list('settled')) SettledCharge.fromRow(a),
    ]..sort((a, b) => a.dueDate.compareTo(b.dueDate));
    return PaymentDetail(
      payment: Payment.fromRow({
        ...row.toMap(),
        'allocations': [
          for (final s in settled)
            Allocation(chargeId: s.chargeId, amount: s.amount).toRow(),
        ],
      }),
      lease: Lease.fromRow(row.object('lease').toMap()),
      settled: settled,
    );
  }

  static const columns =
      'id,lease_id,amount,tax_withheld,allocated_amount,paid_on,method,'
      'reference,tax_certificate_no,notes,receipt_number,voided_at,'
      'void_reason,created_at,'
      'settled:payment_allocations!payment_allocations_payment_fkey(amount,'
      'charge:charges!payment_allocations_charge_fkey(id,kind,period_month,'
      'due_date,description)),'
      'lease:leases!payments_lease_fkey(${Lease.columns})';

  final Payment payment;
  final Lease lease;

  /// Oldest due first.
  final List<SettledCharge> settled;

  Map<String, Object?> toJson() => {
    ...payment.toRow()..remove('allocations'),
    'settled': [for (final s in settled) s.toRow()],
    'lease': lease.toRow(),
  };

  @override
  bool operator ==(Object other) =>
      other is PaymentDetail &&
      other.payment == payment &&
      other.lease == lease &&
      listEquals(other.settled, settled);

  @override
  int get hashCode => Object.hash(payment, lease, Object.hashAll(settled));
}

