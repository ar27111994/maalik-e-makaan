/// What a charge is for (`public.charge_kind`).
enum ChargeKind with DbEnum {
  rent('rent'),
  securityDeposit('security_deposit'),
  electricity('electricity'),
  gas('gas'),
  water('water'),
  internet('internet'),
  maintenance('maintenance'),
  societyCharges('society_charges'),
  lateFee('late_fee'),
  damages('damages'),
  other('other');

  new(this.db);

  @override
  final String db;

  /// The kinds a member adds by hand (LEDGER-02); rent, late fees and the
  /// deposit come from the tenancy's terms.
  static const List<ChargeKind> manual = [
    electricity,
    gas,
    water,
    internet,
    maintenance,
    societyCharges,
    damages,
    other,
  ];

  static ChargeKind parse(String name) => parseDbEnum(values, name);
}

