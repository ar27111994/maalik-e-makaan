/// Where a charge stands on a day, for its status badge.
enum ChargeState {
  /// Still owed after its due date.
  overdue,

  /// Owed, due within [Charge.dueSoonDays] days.
  dueSoon,

  /// Owed, due later.
  notDue,

  /// Settled, with money received for it.
  paid,

  /// Settled by waiving it, with no money received.
  waived,

  /// Cancelled with a reason.
  voided,
}

/// A due on a tenancy (LEDGER-01, LEDGER-02): rent, a late fee, the
/// deposit, a bill or a charge added by hand.
@immutable
final class Charge {
  const new({
    required this.id,
    required this.leaseId,
    required this.kind,
    required this.source,
    required this.dueDate,
    required this.amount,
    this.paidAmount = Money.zero,
    this.waivedAmount = Money.zero,
    this.periodMonth,
    this.description,
    this.relatedChargeId,
    this.waiveReason,
    this.voidedAt,
    this.voidReason,
    this.createdAt = '',
  });

  /// Reads a `charges` row selected with [Charge.columns].
  factory fromRow(Object? json) {
    final row = JsonRow.of(json, 'charge');
    final period = row.optionalDate('period_month');
    final charge = Charge(
      id: row.string('id'),
      leaseId: row.string('lease_id'),
      kind: row.choice('kind', ChargeKind.parse),
      source: row.choice('source', ChargeSource.parse),
      periodMonth: period == null ? null : MonthPeriod.of(period),
      dueDate: row.date('due_date'),
      amount: row.money('amount'),
      paidAmount: row.money('paid_amount'),
      waivedAmount: row.money('waived_amount'),
      description: row.optionalString('description'),
      relatedChargeId: row.optionalString('related_charge_id'),
      waiveReason: row.optionalString('waive_reason'),
      voidedAt: row.optionalTimestamp('voided_at'),
      voidReason: row.optionalString('void_reason'),
      createdAt: row.string('created_at'),
    );
    // `outstanding` is generated by the database: it must agree.
    if (row.money('outstanding') != charge.outstanding) {
      throw const FormatException('outstanding does not add up');
    }
    return charge;
  }

  static const columns =
      'id,lease_id,kind,source,period_month,due_date,amount,paid_amount,'
      'waived_amount,outstanding,description,related_charge_id,waive_reason,'
      'voided_at,void_reason,created_at';

  /// The longest note the database keeps on a charge.
  static const maxDescriptionLength = 200;

  /// The longest reason for waiving or voiding.
  static const maxReasonLength = 300;

  /// How many days before its due date a due counts as due soon (as the
  /// daily `rent_due_soon` notification does).
  static const dueSoonDays = 3;

  final String id;
  final String leaseId;
  final ChargeKind kind;
  final ChargeSource source;

  /// The month a rent (or a bill) is for.
  final MonthPeriod? periodMonth;
  final CalendarDate dueDate;
  final Money amount;
  final Money paidAmount;
  final Money waivedAmount;
  final String? description;

  /// For a late fee, the rent it was charged on.
  final String? relatedChargeId;
  final String? waiveReason;
  final DateTime? voidedAt;
  final String? voidReason;
  final String createdAt;

  /// What is still owed (`amount - paid - waived`, as the database
  /// generates it).
  Money get outstanding => amount - paidAmount - waivedAmount;

  bool get voided => voidedAt != null;

  /// Still owed: neither settled nor voided.
  bool get open => !voided && outstanding.isPositive;

  /// Only a charge added by hand may change its amount (`update_charge`).
  bool get amountEditable => source == ChargeSource.manual;

  PageCursor get cursor => PageCursor(createdAt: createdAt, id: id);

  /// Where it stands on [today].
  ChargeState stateOn(CalendarDate today) {
    if (voided) return ChargeState.voided;
    if (!outstanding.isPositive) {
      return paidAmount.isPositive ? ChargeState.paid : ChargeState.waived;
    }
    if (dueDate.isBefore(today)) return ChargeState.overdue;
    if (!dueDate.isAfter(today.addDays(dueSoonDays))) {
      return ChargeState.dueSoon;
    }
    return ChargeState.notDue;
  }

  /// The row [Charge.fromRow] reads back (the offline cache).
  Map<String, Object?> toRow() => {
    'id': id,
    'lease_id': leaseId,
    'kind': kind.db,
    'source': source.db,
    'period_month': periodMonth?.first.toJson(),
    'due_date': dueDate.toJson(),
    'amount': amount.toJson(),
    'paid_amount': paidAmount.toJson(),
    'waived_amount': waivedAmount.toJson(),
    'outstanding': outstanding.toJson(),
    'description': description,
    'related_charge_id': relatedChargeId,
    'waive_reason': waiveReason,
    'voided_at': voidedAt?.toIso8601String(),
    'void_reason': voidReason,
    'created_at': createdAt,
  };

  @override
  bool operator ==(Object other) =>
      other is Charge && mapEquals(other.toRow(), toRow());

  @override
  int get hashCode => Object.hashAll(toRow().values);
}

