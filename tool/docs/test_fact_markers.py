"""Tests for the marker grammar (python3 -m unittest discover -s tool/docs -p 'test_*.py')."""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import fact_markers
from fact_markers import MarkerError, Rendered

KINDS = {"alpha": "inline", "beta": "inline", "blk": "block", "yml": "yaml"}
OPEN_A = "<!-- docs:alpha from src; generated by make docs, do not edit -->"
OPEN_B = "<!-- docs:beta from src; generated by make docs, do not edit -->"


def rewrite(text: str, path: str = "doc.md", **bodies: str) -> tuple[str, list[str]]:
    spans, errors = fact_markers.scan(path, text, KINDS)
    if errors:
        raise AssertionError(errors)
    return fact_markers.rewrite(text, spans, {k: Rendered("src", v) for k, v in bodies.items()})


def errors_of(text: str, path: str = "doc.md") -> list[MarkerError]:
    return fact_markers.scan(path, text, KINDS)[1]


def rules(errors: list[MarkerError]) -> list[tuple[str, int]]:
    return [(e.rule, e.line) for e in errors]


class InlineTest(unittest.TestCase):
    def test_a_span_mid_line_is_replaced_and_the_text_around_it_kept(self) -> None:
        text = "Before <!-- docs:alpha -->old<!-- /docs:alpha --> after.\nNext line.\n"
        new, changed = rewrite(text, alpha="new")
        self.assertEqual(new, f"Before {OPEN_A}new<!-- /docs:alpha --> after.\nNext line.\n")
        self.assertEqual(changed, ["alpha"])

    def test_a_span_in_a_table_cell(self) -> None:
        text = (
            "| Gate | Value |\n| --- | --- |\n| ui | <!-- docs:alpha -->1%<!-- /docs:alpha --> |\n"
        )
        new, _ = rewrite(text, alpha="95%")
        self.assertEqual(
            new, f"| Gate | Value |\n| --- | --- |\n| ui | {OPEN_A}95%<!-- /docs:alpha --> |\n"
        )

    def test_several_spans_on_one_line_and_one_key_twice(self) -> None:
        text = (
            "x <!-- docs:alpha -->1<!-- /docs:alpha --> y <!-- docs:beta -->2<!-- /docs:beta -->\n"
            "z <!-- docs:alpha -->3<!-- /docs:alpha -->\n"
        )
        new, changed = rewrite(text, alpha="A", beta="B")
        self.assertEqual(
            new,
            f"x {OPEN_A}A<!-- /docs:alpha --> y {OPEN_B}B<!-- /docs:beta -->\n"
            f"z {OPEN_A}A<!-- /docs:alpha -->\n",
        )
        self.assertEqual(changed, ["alpha", "beta", "alpha"])

    def test_a_wrapped_body_with_the_same_words_keeps_its_line_breaks(self) -> None:
        text = f"Scopes: {OPEN_A}`app`, `core`,\n  `ui` and `db`<!-- /docs:alpha -->.\n"
        new, changed = rewrite(text, alpha="`app`, `core`, `ui` and `db`")
        self.assertEqual(new, text)
        self.assertEqual(changed, [])

    def test_a_wrapped_body_with_other_words_is_written_on_one_line(self) -> None:
        text = f"Scopes: {OPEN_A}`app`, `core`,\n  `ui` and `db`<!-- /docs:alpha -->.\n"
        new, _ = rewrite(text, alpha="`app` and `ui`")
        self.assertEqual(new, f"Scopes: {OPEN_A}`app` and `ui`<!-- /docs:alpha -->.\n")

    def test_a_short_hand_typed_marker_is_written_in_full_once(self) -> None:
        text = "See <!--docs:alpha--><!--  /docs:alpha  --> here.\n"
        new, changed = rewrite(text, alpha="14")
        self.assertEqual(new, f"See {OPEN_A}14<!-- /docs:alpha --> here.\n")
        self.assertEqual(changed, ["alpha"])
        again, changed = rewrite(new, alpha="14")
        self.assertEqual((again, changed), (new, []))

    def test_a_span_whose_key_was_not_rendered_is_left_alone(self) -> None:
        text = (
            "a <!-- docs:alpha -->1<!-- /docs:alpha --> b <!-- docs:beta -->2<!-- /docs:beta -->\n"
        )
        new, changed = rewrite(text, beta="3")
        self.assertIn("<!-- docs:alpha -->1<!-- /docs:alpha -->", new)
        self.assertEqual(changed, ["beta"])

    def test_inline_markers_inside_bold_and_after_a_parenthesis_are_fine(self) -> None:
        for line in (
            "**<!-- docs:alpha -->1<!-- /docs:alpha --> journeys**\n",
            "Text (<!-- docs:alpha -->1<!-- /docs:alpha -->) more\n",
            "- item: <!-- docs:alpha -->1<!-- /docs:alpha -->\n",
        ):
            self.assertEqual(errors_of(line), [], line)


class BlockTest(unittest.TestCase):
    def test_a_block_is_replaced_between_blank_lines_and_compared_exactly(self) -> None:
        text = "Intro.\n\n<!-- docs:blk -->\n\nold\n\n<!-- /docs:blk -->\n\nAfter.\n"
        new, changed = rewrite(text, blk="- a\n- b")
        self.assertEqual(
            new,
            "Intro.\n\n<!-- docs:blk from src; generated by make docs, do not edit -->\n\n- a\n- b"
            "\n\n<!-- /docs:blk -->\n\nAfter.\n",
        )
        self.assertEqual(changed, ["blk"])
        self.assertEqual(rewrite(new, blk="- a\n- b"), (new, []))
        # Exact: a blank line more is a change.
        loose = new.replace("- a\n- b", "- a\n\n- b")
        self.assertEqual(rewrite(loose, blk="- a\n- b")[0], new)

    def test_a_block_inside_a_list_item_keeps_its_indentation(self) -> None:
        text = "- Item:\n\n  <!-- docs:blk -->\n\n  old\n\n  <!-- /docs:blk -->\n"
        new, _ = rewrite(text, blk="| a |\n| - |")
        self.assertEqual(
            new,
            "- Item:\n\n  <!-- docs:blk from src; generated by make docs, do not edit -->\n\n"
            "  | a |\n  | - |\n\n  <!-- /docs:blk -->\n",
        )


class YamlTest(unittest.TestCase):
    def test_the_body_is_written_at_the_markers_indentation(self) -> None:
        for indent in ("", "  ", "          "):
            text = f"with:\n{indent}# docs:yml\n{indent}old: 1\n{indent}# /docs:yml\n{indent}x: 2\n"
            new, changed = rewrite(text, "flow.yml", yml="types: |\n  a\n\n  b")
            self.assertEqual(
                new,
                f"with:\n{indent}# docs:yml from src; generated by make docs, do not edit\n"
                f"{indent}types: |\n{indent}  a\n\n{indent}  b\n{indent}# /docs:yml\n{indent}x: 2\n",
            )
            self.assertEqual(changed, ["yml"])
            self.assertEqual(rewrite(new, "flow.yml", yml="types: |\n  a\n\n  b"), (new, []))

    def test_an_empty_pair_is_filled(self) -> None:
        text = "    # docs:yml\n    # /docs:yml\n"
        new, _ = rewrite(text, "flow.yaml", yml="a: 1")
        self.assertEqual(
            new,
            "    # docs:yml from src; generated by make docs, do not edit\n    a: 1\n    # /docs:yml\n",
        )


class RulesTest(unittest.TestCase):
    def test_m1_an_open_marker_without_a_close(self) -> None:
        self.assertEqual(rules(errors_of("a\nb <!-- docs:alpha -->1\n")), [("M1", 2)])

    def test_m2_a_close_marker_without_an_open(self) -> None:
        self.assertEqual(rules(errors_of("a 1<!-- /docs:alpha -->\n")), [("M2", 1)])

    def test_m3_a_close_marker_naming_another_key(self) -> None:
        errors = errors_of("a <!-- docs:alpha -->1\nb<!-- /docs:beta -->\n")
        self.assertEqual(rules(errors), [("M3", 2)])
        self.assertIn("closes docs:alpha (opened on line 1)", errors[0].message)

    def test_m4_markers_nested_inside_a_span(self) -> None:
        text = "a <!-- docs:alpha -->1 <!-- docs:beta -->2<!-- /docs:beta --><!-- /docs:alpha -->\n"
        spans, errors = fact_markers.scan("doc.md", text, KINDS)
        self.assertEqual(rules(errors), [("M4", 1)])
        self.assertEqual(spans, [])

    def test_m5_a_key_that_is_not_in_the_registry(self) -> None:
        self.assertEqual(
            rules(errors_of("a <!-- docs:gamma -->1<!-- /docs:gamma -->\n")), [("M5", 1)]
        )
        self.assertEqual(
            rules(errors_of("a: 1\n# docs:gamma\n# /docs:gamma\n", "f.yml")), [("M5", 2)]
        )
        # A Markdown marker with an unknown key in YAML, and a YAML open marker left unpaired.
        self.assertEqual(
            rules(errors_of("x: 1 # <!-- docs:gamma -->1<!-- /docs:gamma -->\n", "f.yml")),
            [("M5", 1), ("M5", 1)],
        )
        self.assertEqual(
            rules(errors_of("a: 1\n# docs:gamma\nb: 2\n", "f.yml")), [("M1", 2), ("M5", 2)]
        )

    def test_m6_a_kind_that_does_not_suit_the_file(self) -> None:
        self.assertEqual(rules(errors_of("a <!-- docs:yml -->1<!-- /docs:yml -->\n")), [("M6", 1)])
        self.assertEqual(
            rules(errors_of("x:\n  # docs:alpha\n  # /docs:alpha\n", "f.yml")), [("M6", 2)]
        )
        self.assertEqual(
            rules(errors_of("x: 1 # <!-- docs:alpha -->1<!-- /docs:alpha -->\n", "f.yml")),
            [("M6", 1), ("M6", 1)],
        )

    def test_m7_a_marker_outside_the_facts_targets(self) -> None:
        errors = fact_markers.check_placement(
            {"a.md": [("alpha", 3)], "b.md": [("alpha", 7), ("alpha", 9)]}, {"alpha": ("a.md",)}
        )
        self.assertEqual([(e.rule, e.path, e.line) for e in errors], [("M7", "b.md", 7)])
        self.assertIn("add b.md to the fact's targets", errors[0].message)

    def test_m8_a_target_without_its_marker(self) -> None:
        errors = fact_markers.check_placement({"a.md": []}, {"alpha": ("a.md", "c.md")})
        self.assertEqual([(e.rule, e.path) for e in errors], [("M8", "a.md"), ("M8", "c.md")])
        self.assertIn(
            "restore it from git, or remove the file from the fact's targets", errors[0].message
        )

    def test_m7_and_m8_leave_files_no_marker_may_be_in_to_m16(self) -> None:
        errors = fact_markers.check_placement({"CHANGELOG.md": [("alpha", 1)]}, {"alpha": ()})
        self.assertEqual(errors, [])

    def test_m9_an_inline_open_marker_that_begins_its_line(self) -> None:
        for text in (
            "<!-- docs:alpha -->`a`<!-- /docs:alpha --> rest\n",
            "Text that wraps\n  <!-- docs:alpha -->`a`<!-- /docs:alpha --> rest\n",
            "- <!-- docs:alpha -->`a`<!-- /docs:alpha --> rest\n",
            "> 1. <!-- docs:alpha -->`a`<!-- /docs:alpha --> rest\n",
        ):
            errors = errors_of(text)
            self.assertEqual([e.rule for e in errors], ["M9"], text)
        self.assertIn("raw HTML", errors[0].message)

    def test_m10_an_inline_body_with_a_blank_line(self) -> None:
        self.assertEqual(
            rules(errors_of("a <!-- docs:alpha -->1\n\n2<!-- /docs:alpha -->\n")), [("M10", 1)]
        )

    def test_m11_an_inline_body_in_a_table_row_spans_lines(self) -> None:
        errors = errors_of("| a | <!-- docs:alpha -->1\n2<!-- /docs:alpha --> |\n")
        self.assertEqual(rules(errors), [("M11", 1)])

    def test_m12_a_continuation_line_that_starts_a_block(self) -> None:
        for continuation in ("- b", "+ b", "* b", "# b", "> b", "1. b", "2) b", "<b>"):
            text = f"a <!-- docs:alpha -->1,\n  {continuation} c<!-- /docs:alpha -->\n"
            self.assertEqual(rules(errors_of(text)), [("M12", 2)], continuation)
        self.assertEqual(
            rules(errors_of("a <!-- docs:alpha -->1, 2\n<!-- /docs:alpha -->\n")), [("M12", 2)]
        )
        # A line of dashes or equals signs would turn the line above into a heading.
        for underline in ("---", "==="):
            text = f"a <!-- docs:alpha -->1,\n{underline}\nc<!-- /docs:alpha -->\n"
            self.assertEqual(rules(errors_of(text)), [("M12", 2)], underline)
        self.assertEqual(
            errors_of("a <!-- docs:alpha -->1,\n  `b` and -c<!-- /docs:alpha -->\n"), []
        )

    def test_m13_a_block_marker_not_alone_on_its_line(self) -> None:
        errors = errors_of("x <!-- docs:blk -->\n\nb\n\n<!-- /docs:blk --> y\n")
        self.assertEqual(rules(errors), [("M13", 1), ("M13", 5)])

    def test_m14_a_marker_inside_a_fenced_code_block(self) -> None:
        text = "```markdown\nx <!-- docs:alpha -->1<!-- /docs:alpha -->\n```\n"
        self.assertEqual(rules(errors_of(text)), [("M14", 2), ("M14", 2)])

    def test_m15_a_yaml_close_marker_at_another_indentation(self) -> None:
        errors = errors_of("  # docs:yml\n  a: 1\n    # /docs:yml\n", "f.yml")
        self.assertEqual(rules(errors), [("M15", 3)])

    def test_m16_files_no_marker_may_be_in(self) -> None:
        for path in ("CHANGELOG.md", "llms.txt", ".planning/STATE.md"):
            errors = errors_of("a <!-- docs:alpha -->1<!-- /docs:alpha -->\n", path)
            self.assertEqual(rules(errors), [("M16", 1), ("M16", 1)], path)
        errors = errors_of("# docs:yml\n# /docs:yml\n", ".planning/config.yml")
        self.assertEqual(rules(errors), [("M16", 1), ("M16", 2)])

    def test_every_problem_in_a_file_is_reported_with_its_path_and_line(self) -> None:
        text = (
            "<!-- docs:alpha -->`a`<!-- /docs:alpha --> starts a line\n"
            "fine <!-- docs:beta -->b<!-- /docs:beta -->\n"
            "x <!-- docs:gamma -->1<!-- /docs:gamma -->\n"
            "y <!-- docs:beta -->1\n\n2<!-- /docs:beta -->\n"
            "z 9<!-- /docs:alpha -->\n"
        )
        errors = errors_of(text, "docs/x.md")
        self.assertEqual(rules(errors), [("M9", 1), ("M5", 3), ("M10", 4), ("M2", 7)])
        self.assertTrue(all(e.path == "docs/x.md" for e in errors))
        self.assertTrue(str(errors[-1]).startswith("M2 docs/x.md:7: "))


class PlaceholderTest(unittest.TestCase):
    def test_placeholders_in_prose_and_code_are_not_markers(self) -> None:
        text = (
            "Write `<!-- docs:KEY … -->` and `<!-- /docs:KEY -->`, or <!-- docs:… -->.\n"
            "```yaml\n# docs:KEY …\n# /docs:KEY\n```\n"
        )
        self.assertEqual(fact_markers.scan("doc.md", text, KINDS), ([], []))
        self.assertEqual(fact_markers.markers_in(text, "doc.md"), [])
        self.assertEqual(fact_markers.scan("f.yml", "# docs:KEY …\n# /docs:KEY\n", KINDS), ([], []))


class FenceTest(unittest.TestCase):
    def test_a_fence_of_four_backticks_is_not_closed_by_three(self) -> None:
        text = (
            "````markdown\n```\nx <!-- docs:alpha -->1<!-- /docs:alpha -->\n```\n````\n"
            "after <!-- docs:alpha -->2<!-- /docs:alpha -->\n"
        )
        spans, errors = fact_markers.scan("doc.md", text, KINDS)
        self.assertEqual(rules(errors), [("M14", 3), ("M14", 3)])
        self.assertEqual([s.line for s in spans], [6])

    def test_fenced_lines(self) -> None:
        text = "a\n~~~\nb\n```\nc\n~~~~\nd\n   ```sh\ne\n```  \nf\n```unclosed\ng"
        self.assertEqual(fact_markers.fenced_lines(text), {2, 3, 4, 5, 6, 8, 9, 10, 12, 13})

    def test_a_backtick_fence_with_a_backtick_in_its_info_is_not_a_fence(self) -> None:
        self.assertEqual(fact_markers.fenced_lines("```a`b\nc\n"), set())


class HelpersTest(unittest.TestCase):
    def test_normalise_folds_whitespace(self) -> None:
        self.assertEqual(fact_markers.normalise(" a,\n  b\tc "), "a, b c")

    def test_markers_in_lists_every_open_marker(self) -> None:
        text = "a <!-- docs:alpha -->1\n<!-- docs:beta --> x\n"
        self.assertEqual(fact_markers.markers_in(text, "d.md"), [("alpha", 1), ("beta", 2)])
        self.assertEqual(
            fact_markers.markers_in("# docs:yml\n<!-- docs:alpha -->\n", "f.yml"),
            [("alpha", 2), ("yml", 1)],
        )

    def test_syntax_of(self) -> None:
        self.assertEqual(fact_markers.syntax_of("a/b.yml"), "yaml")
        self.assertEqual(fact_markers.syntax_of("a/b.yaml"), "yaml")
        self.assertEqual(fact_markers.syntax_of("llms.txt"), "markdown")

    def test_the_canonical_markers_are_read_back(self) -> None:
        self.assertEqual(
            fact_markers.MD_OPEN.fullmatch(fact_markers.open_marker("a-b2", "Makefile x"))["key"],
            "a-b2",
        )
        self.assertTrue(fact_markers.MD_CLOSE.fullmatch(fact_markers.close_marker("a-b2")))
        self.assertTrue(fact_markers.YAML_OPEN.fullmatch(fact_markers.yaml_open_marker("k", "s")))
        self.assertTrue(fact_markers.YAML_CLOSE.fullmatch(fact_markers.yaml_close_marker("k")))


