class IconError(ValueError):
    """The mark, the tokens or a committed icon cannot be used."""


# --- The mark -------------------------------------------------------------------------------

Point = tuple[float, float]


@dataclass(frozen=True)
class Mark:
    """The brand mark: [strokes] are polylines in a [size] x [size] box."""

    size: float
    tile_radius: float
    stroke_width: float
    path: str
    strokes: tuple[tuple[Point, ...], ...]

    def segments(self) -> tuple[tuple[Point, Point], ...]:
        return tuple(
            (stroke[index], stroke[index + 1])
            for stroke in self.strokes
            for index in range(len(stroke) - 1)
        )

    def reach(self) -> float:
        """How far the stroked house reaches from the tile's centre, in mark units."""
        centre = self.size / 2
        return self.stroke_width / 2 + max(
            math.hypot(x - centre, y - centre) for stroke in self.strokes for x, y in stroke
        )


_NUMBER = r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?"
_PATH_TOKEN = re.compile(rf"[\s,]*(?:(?P<command>[A-Za-z])|(?P<number>{_NUMBER}))[\s,]*")


def _path_tokens(data: str) -> list[str | float]:
    tokens: list[str | float] = []
    position = 0
    while position < len(data):
        match = _PATH_TOKEN.match(data, position)
        if not match or match.end() == position:
            raise IconError(f"cannot read the path at {data[position:]!r}")
        command = match["command"]
        tokens.append(command if command else float(match["number"]))
        position = match.end()
    return tokens


def parse_path(data: str) -> tuple[tuple[Point, ...], ...]:
    """The polylines that an SVG path of straight lines draws (M, L, H, V and Z commands,
    absolute or relative, with repeated arguments). Curves and arcs are refused."""
    tokens = _path_tokens(data)
    strokes: list[list[Point]] = []
    current: list[Point] | None = None
    x = y = 0.0
    start = (0.0, 0.0)
    command = ""
    index = 0

    def number() -> float:
        nonlocal index
        if index >= len(tokens) or isinstance(tokens[index], str):
            raise IconError(f"the path's {command} command lacks a number")
        value = tokens[index]
        index += 1
        return float(value)

    while index < len(tokens):
        item = tokens[index]
        if isinstance(item, str):
            if item not in "MmLlHhVvZz":
                raise IconError(
                    f"the path command {item} is not supported: the mark is drawn in "
                    "straight lines (M, L, H, V, Z)"
                )
            command = item
            index += 1
            if command in "Zz":
                if current is None:
                    raise IconError("the path closes a shape it has not started")
                current.append(start)
                x, y = start
                current = None
                continue
        elif not command or command in "Zz":
            raise IconError("the path must start with M, and a number cannot follow Z")
        if command in "Mm":
            dx, dy = number(), number()
            x, y = (x + dx, y + dy) if command == "m" else (dx, dy)
            start = (x, y)
            current = [start]
            strokes.append(current)
            command = "l" if command == "m" else "L"  # further pairs draw lines
            continue
        if current is None:
            if not strokes:
                raise IconError("the path must start with M")
            current = [start]
            strokes.append(current)
        if command in "Ll":
            dx, dy = number(), number()
            x, y = (x + dx, y + dy) if command == "l" else (dx, dy)
        elif command in "Hh":
            value = number()
            x = x + value if command == "h" else value
        else:
            value = number()
            y = y + value if command == "v" else value
        current.append((x, y))
    if not strokes:
        raise IconError("the path draws nothing")
    return tuple(tuple(stroke) for stroke in strokes if len(stroke) > 1)


def _constant(source: str, name: str, pattern: str) -> str:
    match = re.search(rf"^export const {name} = {pattern};$", source, re.MULTILINE)
    if not match:
        raise IconError(f"{BRAND} must define {name} as a plain literal")
    return match.group(1)


def read_mark(path: Path) -> Mark:
    source = path.read_text(encoding="utf-8")
    viewbox = _constant(source, "MARK_VIEWBOX", r'"([^"]*)"').split()
    if len(viewbox) != 4 or viewbox[:2] != ["0", "0"] or viewbox[2] != viewbox[3]:
        raise IconError(f"MARK_VIEWBOX must be a square from the origin, not {viewbox}")
    number = r"(\d+(?:\.\d+)?)"
    mark_path = _constant(source, "MARK_HOUSE_PATH", r'"([^"]*)"')
    if 'stroke-linecap="round"' not in source or 'stroke-linejoin="round"' not in source:
        raise IconError("the mark's strokes must have round caps and joins, as drawn here")
    return Mark(
        size=float(viewbox[2]),
        tile_radius=float(_constant(source, "MARK_TILE_RADIUS", number)),
        stroke_width=float(_constant(source, "MARK_STROKE_WIDTH", number)),
        path=mark_path,
        strokes=parse_path(mark_path),
    )


@dataclass(frozen=True)
class Palette:
    primary: str
    on_primary: str
    background: str
    dark_primary: str
    dark_on_primary: str


def read_palette(path: Path) -> Palette:
    colours = json.loads(path.read_text(encoding="utf-8")).get("color", {})

    def colour(mode: str, role: str) -> str:
        try:
            value = colours[mode][role]["$value"]["hex"]
        except (KeyError, TypeError):
            raise IconError(f"no colour token {mode}.{role}") from None
        if not isinstance(value, str) or not HEX.match(value):
            raise IconError(f"colour token {mode}.{role} is not #RRGGBB: {value!r}")
        return value.upper()

    return Palette(
        primary=colour("light", "primary"),
        on_primary=colour("light", "onPrimary"),
        background=colour("light", "bg"),
        dark_primary=colour("dark", "primary"),
        dark_on_primary=colour("dark", "onPrimary"),
    )


def read_app_name(path: Path) -> str:
    name = json.loads(path.read_text(encoding="utf-8")).get("appName")
    if not isinstance(name, str) or not name.strip():
        raise IconError(f"{APP_STRINGS} has no appName")
    return name


# --- Rasterising ----------------------------------------------------------------------------


def _rgb(colour: str) -> tuple[int, int, int]:
    return int(colour[1:3], 16), int(colour[3:5], 16), int(colour[5:7], 16)


def _coverage(distance: float) -> int:
    """0-255 coverage of a pixel whose centre is [distance] pixels outside an edge (negative:
    inside); a one-pixel ramp across the edge."""
    share = 0.5 - distance
    if share <= 0:
        return 0
    if share >= 1:
        return 255
    return int(share * 255 + 0.5)


Segment = tuple[float, float, float, float]  # start x, start y, dx, dy in pixels

# A pixel's square reaches this far from its centre: a stroke further away covers none of it.
HALF_DIAGONAL = math.sqrt(0.5)
# Pixels that two strokes cover in part (where the house's lines meet) are measured on a grid
# of this many samples a side: one distance ramp cannot add two strokes' coverage.
SAMPLES = 16


def _distance(x: float, y: float, segment: Segment) -> float:
    x0, y0, dx, dy = segment
    px, py = x - x0, y - y0
    length2 = dx * dx + dy * dy
    along = (px * dx + py * dy) / length2 if length2 else 0.0
    along = 0.0 if along < 0 else 1.0 if along > 1 else along
    ex, ey = px - along * dx, py - along * dy
    return math.sqrt(ex * ex + ey * ey)


@functools.lru_cache(maxsize=32)
def stroke_coverage(mark: Mark, size: int, scale: float, offset: float) -> bytes:
    """Coverage of the house in a [size] x [size] image where the mark's point (u, v) lands at
    pixel coordinates (offset + u * scale, offset + v * scale)."""
    radius = mark.stroke_width / 2 * scale
    nearest = [math.inf] * (size * size)
    touched = bytearray(size * size)
    shared: set[int] = set()
    segments = [
        (offset + u0 * scale, offset + v0 * scale, (u1 - u0) * scale, (v1 - v0) * scale)
        for (u0, v0), (u1, v1) in mark.segments()
    ]
    for segment in segments:
        x0, y0, dx, dy = segment
        reach = radius + 1
        left = max(0, math.floor(min(x0, x0 + dx) - reach))
        right = min(size - 1, math.ceil(max(x0, x0 + dx) + reach))
        top = max(0, math.floor(min(y0, y0 + dy) - reach))
        bottom = min(size - 1, math.ceil(max(y0, y0 + dy) + reach))
        for row in range(top, bottom + 1):
            y = row + 0.5
            base = row * size
            for column in range(left, right + 1):
                index = base + column
                distance = _distance(column + 0.5, y, segment)
                if distance < radius + HALF_DIAGONAL:
                    if touched[index]:
                        shared.add(index)
                    touched[index] = 1
                if distance < nearest[index]:
                    nearest[index] = distance
    coverage = bytearray(_coverage(distance - radius) for distance in nearest)
    for index in sorted(shared):
        if nearest[index] <= radius - HALF_DIAGONAL:
            continue  # wholly inside one stroke
        row, column = divmod(index, size)
        near = [
            segment
            for segment in segments
            if _distance(column + 0.5, row + 0.5, segment) < radius + HALF_DIAGONAL
        ]
        inside = sum(
            any(
                _distance(column + (sx + 0.5) / SAMPLES, row + (sy + 0.5) / SAMPLES, segment)
                <= radius
                for segment in near
            )
            for sy in range(SAMPLES)
            for sx in range(SAMPLES)
        )
        coverage[index] = int(inside * 255 / (SAMPLES * SAMPLES) + 0.5)
    return bytes(coverage)


def shape_coverage(shape: str, size: int, side: float, radius: float) -> bytes:
    """Coverage of a centred square ("square", "tile" with corners of [radius] pixels) or circle
    ("circle") [side] pixels across, in a [size] x [size] image."""
    centre = size / 2
    half = side / 2
    if shape == "circle":
        radius = half
    elif shape == "square":
        radius = 0.0
    elif shape != "tile":
        raise IconError(f"unknown shape {shape}")
    straight = half - radius
    cells = bytearray(size * size)
    for row in range(size):
        qy = abs(row + 0.5 - centre) - straight
        for column in range(size):
            qx = abs(column + 0.5 - centre) - straight
            outside = math.hypot(max(qx, 0.0), max(qy, 0.0))
            inside = min(max(qx, qy), 0.0)
            cells[row * size + column] = _coverage(outside + inside - radius)
    return bytes(cells)


@dataclass(frozen=True)
class Icon:
    """One PNG of the mark: the house in [glyph] on a [shape] of [tile], the shape filling
    [share] of the [size] x [size] canvas; the house keeps its place on the mark's tile."""

    path: str
    size: int
    shape: str  # "square" (to the edges), "tile" (the mark's rounded tile) or "circle"
    share: float
    tile: str
    glyph: str
    alpha: bool  # write an alpha channel; an opaque icon must fill its canvas


def render(mark: Mark, icon: Icon) -> tuple[bytes, bytes]:
    """The PNG header fields (IHDR) and the pixels of [icon], row after row."""
    side = icon.size * icon.share
    scale = side / mark.size
    offset = (icon.size - side) / 2
    glyph = stroke_coverage(mark, icon.size, scale, offset)
    full = icon.shape == "square" and icon.share == 1
    if not icon.alpha and not full:
        raise IconError(f"{icon.path}: an icon without alpha must fill its canvas")
    shape = None if full else shape_coverage(icon.shape, icon.size, side, mark.tile_radius * scale)
    tile, ink = _rgb(icon.tile), _rgb(icon.glyph)
    # The house lies where the shape is opaque (check_geometry), so a pixel is the tile's colour
    # blended towards the house's by the house's coverage, and its alpha is the shape's coverage:
    # one lookup table per colour channel.
    tables = [
        bytes(int(t + (g - t) * level / 255 + 0.5) for level in range(256))
        for t, g in zip(tile, ink, strict=True)
    ]
    channels = 4 if icon.alpha else 3
    pixels = bytearray(icon.size * icon.size * channels)
    for channel, table in enumerate(tables):
        pixels[channel::channels] = glyph.translate(table)
    if icon.alpha:
        pixels[3::4] = shape if shape is not None else b"\xff" * (icon.size * icon.size)
    header = struct.pack(">IIBBBBB", icon.size, icon.size, 8, RGBA if icon.alpha else RGB, 0, 0, 0)
    return header, bytes(pixels)


def _chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def _stride(header: bytes) -> int:
    """The bytes in a row of an image this tool reads: 8-bit RGB or RGBA, not interlaced."""
    width, _, depth, colour, _, _, interlace = struct.unpack(">IIBBBBB", header)
    if depth != 8 or colour not in (RGB, RGBA) or interlace:
        raise IconError(f"cannot read {describe(header)}")
    return width * (4 if colour == RGBA else 3)


def png_file(header: bytes, pixels: bytes) -> bytes:
    stride = _stride(header)
    scanlines = b"".join(
        b"\x00" + pixels[start : start + stride]  # filter type 0 (none)
        for start in range(0, len(pixels), stride)
    )
    return (
        PNG_SIGNATURE
        + _chunk(b"IHDR", header)
        + _chunk(b"IDAT", zlib.compress(scanlines, 9))
        + _chunk(b"IEND", b"")
    )


def describe(header: bytes) -> str:
    """An image's format, from its PNG header fields."""
    width, height, depth, colour, _, _, interlace = struct.unpack(">IIBBBBB", header)
    kind = COLOUR_TYPES.get(colour, f"colour type {colour}")
    return f"a {width} x {height}, {depth}-bit {kind} image" + (
        " (interlaced)" if interlace else ""
    )


def png_parts(data: bytes) -> tuple[bytes, bytes]:
    """The header fields (IHDR) and the decompressed, still filtered scanlines of a PNG file."""
    if not data.startswith(PNG_SIGNATURE):
        raise IconError("not a PNG file")
    position = len(PNG_SIGNATURE)
    header = b""
    compressed = []
    while position + 8 <= len(data):
        (length,) = struct.unpack(">I", data[position : position + 4])
        kind = data[position + 4 : position + 8]
        body = data[position + 8 : position + 8 + length]
        if kind == b"IHDR":
            header = body
        elif kind == b"IDAT":
            compressed.append(body)
        elif kind == b"IEND":
            break
        position += 12 + length
    if len(header) != 13 or not compressed:
        raise IconError("the PNG file has no valid header or no image data")
    try:
        return header, zlib.decompress(b"".join(compressed))
    except zlib.error as error:
        raise IconError(f"the PNG file's image data is damaged ({error})") from None


def _paeth(left: int, up: int, corner: int) -> int:
    estimate = left + up - corner
    to_left, to_up, to_corner = abs(estimate - left), abs(estimate - up), abs(estimate - corner)
    if to_left <= to_up and to_left <= to_corner:
        return left
    return up if to_up <= to_corner else corner


def unfilter(header: bytes, scanlines: bytes) -> bytes:
    """The pixels of an image whose rows each start with a PNG filter type (0 to 4)."""
    stride = _stride(header)
    _, height = struct.unpack(">II", header[:8])
    step = 4 if header[9] == RGBA else 3  # bytes per pixel: filters look at the pixel before
    if len(scanlines) != height * (stride + 1):
        raise IconError("the PNG file's image data has the wrong length")
    pixels = bytearray()
    above = bytes(stride)
    for start in range(0, len(scanlines), stride + 1):
        kind = scanlines[start]
        row = bytearray(scanlines[start + 1 : start + 1 + stride])
        if kind == 1:  # Sub
            for index in range(step, stride):
                row[index] = (row[index] + row[index - step]) & 0xFF
        elif kind == 2:  # Up
            row = bytearray((value + up) & 0xFF for value, up in zip(row, above, strict=True))
        elif kind == 3:  # Average
            for index in range(stride):
                left = row[index - step] if index >= step else 0
                row[index] = (row[index] + (left + above[index]) // 2) & 0xFF
        elif kind == 4:  # Paeth
            for index in range(stride):
                left, corner = (row[index - step], above[index - step]) if index >= step else (0, 0)
                row[index] = (row[index] + _paeth(left, above[index], corner)) & 0xFF
        elif kind != 0:
            raise IconError(f"the PNG file has a row with the unknown filter type {kind}")
        pixels += row
        above = row
    return bytes(pixels)


def png_image(data: bytes) -> tuple[bytes, bytes]:
    """The header fields and the pixels of a PNG file this tool can read."""
    header, scanlines = png_parts(data)
    return header, unfilter(header, scanlines)


