# --- Rasterising ----------------------------------------------------------------------------


def _rgb(colour: str) -> tuple[int, int, int]:
    return int(colour[1:3], 16), int(colour[3:5], 16), int(colour[5:7], 16)


def _coverage(distance: float) -> int:
    """0-255 coverage of a pixel whose centre is [distance] pixels outside an edge (negative:
    inside); a one-pixel ramp across the edge."""
    share = 0.5 - distance
    if share <= 0:
        return 0
    if share >= 1:
        return 255
    return int(share * 255 + 0.5)


# Arcs are drawn as chords that stray at most this far from them, in pixels. A convex arc runs
# at most 4 pixels inside one pixel's square, so the chords move no pixel's coverage by more than
# a quarter of one level in 255: every pixel stays the exact coverage, rounded up or down.
FLATNESS = 0.25 / 255 / 4


def _add_edge(cells: list[float], size: int, start: Point, end: Point) -> None:
    """Adds an edge to [cells], row by row: for each pixel it crosses, the change from the pixel
    before in the share of the row's height to the right of the edge, signed by its direction
    (downwards adds). A running sum along the rows then gives each pixel its share of the shape,
    exactly, as in font-rs. The edge lies in the canvas, its x up to [size]: the last column's
    change falls into the next row's first cell, where the running sum needs it."""
    (x0, y0), (x1, y1) = start, end
    if y0 == y1:
        return  # a level edge leaves no area to its right
    sign = 1.0
    if y0 > y1:
        (x0, y0), (x1, y1), sign = (x1, y1), (x0, y0), -1.0
    slope = (x1 - x0) / (y1 - y0)
    for row in range(math.floor(y0), math.ceil(y1)):
        top, bottom = max(float(row), y0), min(row + 1.0, y1)
        xa = x0 + (top - y0) * slope
        xb = x1 if bottom == y1 else x0 + (bottom - y0) * slope
        height = (bottom - top) * sign
        left, right = (xa, xb) if xa <= xb else (xb, xa)
        first, last = math.floor(left), math.ceil(right)
        base = row * size
        if last <= first + 1:  # within one pixel: what lies right of the edge's middle
            inside = (xa + xb) / 2 - first
            cells[base + first] += height * (1 - inside)
            cells[base + first + 1] += height * inside
            continue
        across = 1 / (right - left)  # the share of the height spent crossing each whole pixel
        head, tail = first + 1 - left, right - (last - 1)  # how far it crosses the end pixels
        head_area = across * head * head / 2
        tail_area = across * tail * tail / 2
        cells[base + first] += height * head_area
        if last == first + 2:
            cells[base + first + 1] += height * (1 - head_area - tail_area)
        else:
            second = across * (head + 0.5)
            cells[base + first + 1] += height * (second - head_area)
            for column in range(first + 2, last - 1):
                cells[base + column] += height * across
            before_tail = second + (last - first - 3) * across
            cells[base + last - 1] += height * (1 - before_tail - tail_area)
        cells[base + last] += height * tail_area


def area_coverage(polygons: Sequence[Sequence[Point]], size: int) -> list[float]:
    """The share (0 to 1) of each pixel of a [size] x [size] image, row after row, that the
    closed [polygons] (in pixel coordinates) cover: exact wherever no point is wound twice or
    both ways, which check_outline ensures for the mark. The polygons must lie on the canvas,
    their edges included (check_geometry keeps the mark well inside it); one that does not is
    refused, since moving its corners onto the canvas would move its sloping edges too."""
    if any(not (0 <= x <= size and 0 <= y <= size) for polygon in polygons for x, y in polygon):
        raise IconError(f"the glyph runs off the {size} x {size} canvas")
    cells = [0.0] * (size * size + 2)  # the last row's changes may fall two cells past its end
    for polygon in polygons:
        for start, end in _sides(polygon):
            _add_edge(cells, size, start, end)
    return [min(abs(total), 1.0) for total in itertools.accumulate(cells[: size * size])]


@functools.lru_cache(maxsize=32)
def fill_coverage(mark: Mark, size: int, scale: float, offset: float) -> bytes:
    """Coverage (0 to 255) of the glyph in a [size] x [size] image where the mark's point
    (u, v) lands at pixel coordinates (offset + u * scale, offset + v * scale)."""
    polygons = [
        [(offset + u * scale, offset + v * scale) for u, v in polygon]
        for polygon in mark.polygons(FLATNESS / scale)
    ]
    return bytes(int(share * 255 + 0.5) for share in area_coverage(polygons, size))


def shape_coverage(shape: str, size: int, side: float, radius: float) -> bytes:
    """Coverage of a centred square ("square", "tile" with corners of [radius] pixels) or circle
    ("circle") [side] pixels across, in a [size] x [size] image."""
    centre = size / 2
    half = side / 2
    if shape == "circle":
        radius = half
    elif shape == "square":
        radius = 0.0
    elif shape != "tile":
        raise IconError(f"unknown shape {shape}")
    straight = half - radius
    cells = bytearray(size * size)
    for row in range(size):
        qy = abs(row + 0.5 - centre) - straight
        for column in range(size):
            qx = abs(column + 0.5 - centre) - straight
            outside = math.hypot(max(qx, 0.0), max(qy, 0.0))
            inside = min(max(qx, qy), 0.0)
            cells[row * size + column] = _coverage(outside + inside - radius)
    return bytes(cells)


@dataclass(frozen=True)
class Icon:
    """One PNG of the mark: the house in [glyph] on a [shape] of [tile], the shape filling
    [share] of the [size] x [size] canvas; the house keeps its place on the mark's tile, drawn at
    [glyph_scale] of the tile's scale about its centre."""

    path: str
    size: int
    shape: str  # "square" (to the edges), "tile" (the mark's rounded tile) or "circle"
    share: float
    tile: str
    glyph: str
    alpha: bool  # write an alpha channel; an opaque icon must fill its canvas
    glyph_scale: float = 1.0


def render(mark: Mark, icon: Icon) -> tuple[bytes, bytes]:
    """The PNG header fields (IHDR) and the pixels of [icon], row after row."""
    side = icon.size * icon.share
    scale = side * icon.glyph_scale / mark.size
    offset = (icon.size - mark.size * scale) / 2
    glyph = fill_coverage(mark, icon.size, scale, offset)
    full = icon.shape == "square" and icon.share == 1
    if not icon.alpha and not full:
        raise IconError(f"{icon.path}: an icon without alpha must fill its canvas")
    radius = mark.tile_radius * side / mark.size
    shape = None if full else shape_coverage(icon.shape, icon.size, side, radius)
    tile, ink = _rgb(icon.tile), _rgb(icon.glyph)
    # The house lies where the shape is opaque (check_geometry), so a pixel is the tile's colour
    # blended towards the house's by the house's coverage, and its alpha is the shape's coverage:
    # one lookup table per colour channel.
    tables = [
        bytes(int(t + (g - t) * level / 255 + 0.5) for level in range(256))
        for t, g in zip(tile, ink, strict=True)
    ]
    channels = 4 if icon.alpha else 3
    pixels = bytearray(icon.size * icon.size * channels)
    for channel, table in enumerate(tables):
        pixels[channel::channels] = glyph.translate(table)
    if icon.alpha:
        pixels[3::4] = shape if shape is not None else b"\xff" * (icon.size * icon.size)
    header = struct.pack(">IIBBBBB", icon.size, icon.size, 8, RGBA if icon.alpha else RGB, 0, 0, 0)
    return header, bytes(pixels)


def _chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def _stride(header: bytes) -> int:
    """The bytes in a row of an image this tool reads: 8-bit RGB or RGBA, not interlaced."""
    width, _, depth, colour, _, _, interlace = struct.unpack(">IIBBBBB", header)
    if depth != 8 or colour not in (RGB, RGBA) or interlace:
        raise IconError(f"cannot read {describe(header)}")
    return width * (4 if colour == RGBA else 3)


def png_file(header: bytes, pixels: bytes) -> bytes:
    stride = _stride(header)
    scanlines = b"".join(
        b"\x00" + pixels[start : start + stride]  # filter type 0 (none)
        for start in range(0, len(pixels), stride)
    )
    return (
        PNG_SIGNATURE
        + _chunk(b"IHDR", header)
        + _chunk(b"IDAT", zlib.compress(scanlines, 9))
        + _chunk(b"IEND", b"")
    )


def describe(header: bytes) -> str:
    """An image's format, from its PNG header fields."""
    width, height, depth, colour, _, _, interlace = struct.unpack(">IIBBBBB", header)
    kind = COLOUR_TYPES.get(colour, f"colour type {colour}")
    return f"a {width} x {height}, {depth}-bit {kind} image" + (
        " (interlaced)" if interlace else ""
    )


def _chunk_name(kind: bytes) -> str:
    """A chunk's type as the PNG specification spells it (four ASCII letters), or its bytes."""
    return kind.decode("ascii") if kind.isalpha() else repr(kind)


def _follow(count: int, what: str) -> str:
    return f"{count} {'byte follows' if count == 1 else 'bytes follow'} {what}"


# The critical chunks a PNG reader must understand; PLTE is allowed though the icons never use it.
KNOWN_CRITICAL_CHUNKS = frozenset({b"IHDR", b"PLTE", b"IDAT", b"IEND"})


def png_chunks(data: bytes) -> list[tuple[bytes, bytes]]:
    """The chunks of a PNG file, as (type, data) pairs, once its structure is sound: the
    signature, then whole chunks whose checksums (CRC-32 of the type and the data) match, IHDR
    first and only there, the IDAT chunks in one unbroken run, no critical chunk this reader does
    not know, and an empty IEND last, with nothing after it. A file damaged in storage or in
    transit (a flipped bit, a file cut short, bytes appended) fails here, even when its image
    data would still decode, and so does a file that libpng would refuse."""
    if not data.startswith(PNG_SIGNATURE):
        raise IconError("not a PNG file")
    found: list[tuple[bytes, bytes]] = []
    position = len(PNG_SIGNATURE)
    while not found or found[-1][0] != b"IEND":
        if position == len(data):
            raise DamagedPngError("the file ends before an IEND chunk")
        if position + 8 > len(data):
            raise DamagedPngError("the file ends part-way through a chunk")
        length, kind = struct.unpack(">I4s", data[position : position + 8])
        name = _chunk_name(kind)
        end = position + 8 + length  # where the chunk's data ends and its checksum starts
        if end + 4 > len(data):
            raise DamagedPngError(f"the file ends part-way through the {name} chunk")
        body = data[position + 8 : end]
        if data[end : end + 4] != struct.pack(">I", zlib.crc32(kind + body)):
            raise DamagedPngError(f"bad checksum in {name}")
        if not found and kind != b"IHDR":
            raise DamagedPngError(f"the first chunk is {name}, not IHDR")
        if found and kind == b"IHDR":
            raise DamagedPngError("a second IHDR chunk")
        if kind[0] & 0x20 == 0 and kind not in KNOWN_CRITICAL_CHUNKS:
            # An upper-case first letter marks a chunk a decoder must understand to read the file.
            raise DamagedPngError(f"an unknown critical chunk, {name}")
        if kind == b"IDAT" and found[-1][0] != b"IDAT" and any(k == b"IDAT" for k, _ in found):
            raise DamagedPngError("the IDAT chunks are not one unbroken run")
        found.append((kind, body))
        position = end + 4
    if found[-1][1]:
        raise DamagedPngError("the IEND chunk is not empty")
    if position < len(data):
        raise DamagedPngError(_follow(len(data) - position, "the IEND chunk"))
    return found


def png_parts(data: bytes) -> tuple[bytes, bytes]:
    """The header fields (IHDR) and the decompressed, still filtered scanlines of a PNG file."""
    found = png_chunks(data)
    header = found[0][1]
    compressed = [body for kind, body in found if kind == b"IDAT"]
    if len(header) != 13 or not compressed:
        raise IconError("the PNG file has no valid header or no image data")
    stream = zlib.decompressobj()
    try:
        scanlines = stream.decompress(b"".join(compressed))
    except zlib.error as error:
        raise DamagedPngError(f"the compressed image data is damaged ({error})") from None
    if not stream.eof:
        raise DamagedPngError("the compressed image data is cut short")
    if stream.unused_data:
        raise DamagedPngError(_follow(len(stream.unused_data), "the compressed image data"))
    return header, scanlines


def _paeth(left: int, up: int, corner: int) -> int:
    estimate = left + up - corner
    to_left, to_up, to_corner = abs(estimate - left), abs(estimate - up), abs(estimate - corner)
    if to_left <= to_up and to_left <= to_corner:
        return left
    return up if to_up <= to_corner else corner


def unfilter(header: bytes, scanlines: bytes) -> bytes:
    """The pixels of an image whose rows each start with a PNG filter type (0 to 4)."""
    stride = _stride(header)
    _, height = struct.unpack(">II", header[:8])
    step = 4 if header[9] == RGBA else 3  # bytes per pixel: filters look at the pixel before
    if len(scanlines) != height * (stride + 1):
        raise IconError("the PNG file's image data has the wrong length")
    pixels = bytearray()
    above = bytes(stride)
    for start in range(0, len(scanlines), stride + 1):
        kind = scanlines[start]
        row = bytearray(scanlines[start + 1 : start + 1 + stride])
        if kind == 1:  # Sub
            for index in range(step, stride):
                row[index] = (row[index] + row[index - step]) & 0xFF
        elif kind == 2:  # Up
            row = bytearray((value + up) & 0xFF for value, up in zip(row, above, strict=True))
        elif kind == 3:  # Average
            for index in range(stride):
                left = row[index - step] if index >= step else 0
                row[index] = (row[index] + (left + above[index]) // 2) & 0xFF
        elif kind == 4:  # Paeth
            for index in range(stride):
                left, corner = (row[index - step], above[index - step]) if index >= step else (0, 0)
                row[index] = (row[index] + _paeth(left, above[index], corner)) & 0xFF
        elif kind != 0:
            raise IconError(f"the PNG file has a row with the unknown filter type {kind}")
        pixels += row
        above = row
    return bytes(pixels)


def png_image(data: bytes) -> tuple[bytes, bytes]:
    """The header fields and the pixels of a PNG file this tool can read."""
    header, scanlines = png_parts(data)
    return header, unfilter(header, scanlines)


