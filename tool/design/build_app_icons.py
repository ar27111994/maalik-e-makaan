def icons(palette: Palette) -> list[Icon]:
    light = {"tile": palette.primary, "glyph": palette.on_primary}
    found = []
    for density, size in ANDROID_DENSITIES:
        folder = f"{RES}/mipmap-{density}"
        found += [
            Icon(
                f"{folder}/ic_launcher.png", size, "tile", LEGACY_SQUARE_SHARE, alpha=True, **light
            ),
            Icon(
                f"{folder}/ic_launcher_round.png",
                size,
                "circle",
                LEGACY_CIRCLE_SHARE,
                alpha=True,
                **light,
            ),
        ]
    found += [
        # Google Play wants a full square, 32-bit PNG; it rounds the corners itself.
        Icon(PLAY_ICON, 512, "square", 1, alpha=True, **light),
        # iOS masks the icon itself and refuses transparency in it.
        Icon(f"{APP_ICON_SET}/AppIcon.png", 1024, "square", 1, alpha=False, **light),
        # Dark: the dark theme's colours, as the house in `primary` on `onPrimary`, so the icon is
        # dark like the home screen around it.
        Icon(
            f"{APP_ICON_SET}/AppIcon-dark.png",
            1024,
            "square",
            1,
            tile=palette.dark_on_primary,
            glyph=palette.dark_primary,
            alpha=False,
        ),
        Icon(
            f"{APP_ICON_SET}/AppIcon-tinted.png",
            1024,
            "square",
            1,
            tile=TINTED_BACKGROUND,
            glyph=TINTED_GLYPH,
            alpha=False,
        ),
        # The web: the tile as the website draws it, and full squares for masks (and for iOS,
        # whose home screen takes the apple-touch-icon in index.html).
        Icon(f"{WEB}/favicon.png", 32, "tile", 1, alpha=True, **light),
    ]
    for size in (192, 512):
        found += [
            Icon(f"{WEB}/icons/Icon-{size}.png", size, "tile", 1, alpha=True, **light),
            Icon(f"{WEB}/icons/Icon-maskable-{size}.png", size, "square", 1, alpha=False, **light),
        ]
    return found


def _xml(body: str) -> str:
    return f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {GENERATED_BY} -->\n{body}'


def adaptive_icon_xml() -> str:
    return _xml(
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n'
        "</adaptive-icon>\n"
    )


def _decimal(value: float) -> str:
    return f"{value:.4f}".rstrip("0").rstrip(".")


def foreground_xml(mark: Mark, palette: Palette) -> str:
    scale = ADAPTIVE_VISIBLE_DP / mark.size
    offset = (ADAPTIVE_CANVAS_DP - ADAPTIVE_VISIBLE_DP) / 2
    canvas = ADAPTIVE_CANVAS_DP
    return _xml(
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{canvas}dp"\n'
        f'    android:height="{canvas}dp"\n'
        f'    android:viewportWidth="{canvas}"\n'
        f'    android:viewportHeight="{canvas}">\n'
        f"    <!-- The mark's tile maps onto the central {ADAPTIVE_VISIBLE_DP} dp that every"
        " launcher shows. -->\n"
        "    <group\n"
        f'        android:translateX="{_decimal(offset)}"\n'
        f'        android:translateY="{_decimal(offset)}"\n'
        f'        android:scaleX="{_decimal(scale)}"\n'
        f'        android:scaleY="{_decimal(scale)}">\n'
        "        <path\n"
        f'            android:pathData="{mark.path}"\n'
        f'            android:strokeColor="{palette.on_primary}"\n'
        f'            android:strokeWidth="{_decimal(mark.stroke_width)}"\n'
        '            android:strokeLineCap="round"\n'
        '            android:strokeLineJoin="round" />\n'
        "    </group>\n"
        "</vector>\n"
    )


def background_xml(palette: Palette) -> str:
    return _xml(
        "<resources>\n"
        f'    <color name="ic_launcher_background">{palette.primary}</color>\n'
        "</resources>\n"
    )


def contents_json() -> str:
    def image(filename: str, appearance: str | None) -> dict:
        entry: dict = {
            "filename": filename,
            "idiom": "universal",
            "platform": "ios",
            "size": "1024x1024",
        }
        if appearance:
            entry["appearances"] = [{"appearance": "luminosity", "value": appearance}]
        return entry

    contents = {
        "images": [
            image("AppIcon.png", None),
            image("AppIcon-dark.png", "dark"),
            image("AppIcon-tinted.png", "tinted"),
        ],
        "info": {"author": "xcode", "version": 1},
    }
    # Xcode's own layout: sorted keys, two-space indent, " : " between key and value.
    return json.dumps(contents, indent=2, separators=(",", " : "), sort_keys=True) + "\n"


def manifest_json(current: str, name: str, palette: Palette) -> str:
    try:
        manifest = json.loads(current) if current else {}
    except json.JSONDecodeError as error:
        raise IconError(f"{WEB}/manifest.json is not valid JSON ({error})") from None
    manifest.update(
        name=name,
        short_name=name,
        background_color=palette.background,
        theme_color=palette.primary,
        icons=[
            {"src": f"icons/Icon-{size}.png", "sizes": f"{size}x{size}", "type": "image/png"}
            for size in (192, 512)
        ]
        + [
            {
                "src": f"icons/Icon-maskable-{size}.png",
                "sizes": f"{size}x{size}",
                "type": "image/png",
                "purpose": "maskable",
            }
            for size in (192, 512)
        ],
    )
    return json.dumps(manifest, indent=4, ensure_ascii=False) + "\n"


def check_geometry(mark: Mark) -> None:
    """Refuses a mark whose house a mask would cut. A house inside these circles also lies
    inside the tile, the rounded tile and the legacy circle, wholly opaque there."""
    reach = mark.reach()
    adaptive = reach * ADAPTIVE_VISIBLE_DP / mark.size
    if adaptive > ADAPTIVE_SAFE_DIAMETER_DP / 2:
        raise IconError(
            f"the house reaches {adaptive:.1f} dp from the adaptive icon's centre, past the "
            f"{ADAPTIVE_SAFE_DIAMETER_DP / 2:g} dp safe zone"
        )
    if reach > mark.size * MASKABLE_SAFE_SHARE / 2:
        raise IconError("the house reaches past a maskable icon's safe circle")


@dataclass(frozen=True)
class Outputs:
    texts: dict[str, str]
    images: dict[str, tuple[bytes, bytes]]  # path: (PNG header, pixels)
    owned_folders: tuple[str, ...]  # folders that hold nothing else


def build(root: Path) -> Outputs:
    mark = read_mark(root / BRAND)
    palette = read_palette(root / TOKENS)
    name = read_app_name(root / APP_STRINGS)
    check_geometry(mark)
    manifest = root / WEB / "manifest.json"
    adaptive = adaptive_icon_xml()
    texts = {
        f"{RES}/mipmap-anydpi-v26/ic_launcher.xml": adaptive,
        f"{RES}/mipmap-anydpi-v26/ic_launcher_round.xml": adaptive,
        f"{RES}/drawable/ic_launcher_foreground.xml": foreground_xml(mark, palette),
        f"{RES}/values/ic_launcher_background.xml": background_xml(palette),
        f"{APP_ICON_SET}/Contents.json": contents_json(),
        f"{WEB}/manifest.json": manifest_json(
            manifest.read_text(encoding="utf-8") if manifest.exists() else "", name, palette
        ),
    }
    images = {icon.path: render(mark, icon) for icon in icons(palette)}
    return Outputs(texts, images, owned_folders=(APP_ICON_SET,))


def _clutter(path: Path) -> bool:
    """Whether [path] is a file that an operating system or an editor leaves in a folder it
    shows or edits (all of them in .gitignore): hidden files such as Finder's .DS_Store and swap
    files, Windows' Thumbs.db, and backups ending in ~. They are not the folder's content."""
    return path.name.startswith(".") or path.name == "Thumbs.db" or path.name.endswith("~")


def _stale_files(root: Path, outputs: Outputs) -> list[Path]:
    known = {root / path for path in [*outputs.texts, *outputs.images]}
    return sorted(
        path
        for folder in outputs.owned_folders
        if (root / folder).is_dir()
        for path in (root / folder).iterdir()
        if path.is_file() and path not in known and not _clutter(path)
    )


def _image_problem(root: Path, path: str, header: bytes, pixels: bytes) -> str | None:
    """What keeps the file at [path] from being the generated image, or None if it is."""
    file = root / path
    if not file.is_file():
        return f"{path} is missing"
    try:
        found, scanlines = png_parts(file.read_bytes())
        if found != header:
            return f"{path} is {describe(found)}, not {describe(header)}"
        if unfilter(header, scanlines) != pixels:
            return f"{path} does not hold the generated pixels"
    except IconError as error:
        return f"{path} cannot be read: {error}"
    return None


def problems(root: Path) -> list[str]:
    """What is missing or stale; an empty list means the committed icons are current."""
    outputs = build(root)
    found = []
    for path, text in outputs.texts.items():
        file = root / path
        if not file.is_file() or file.read_text(encoding="utf-8") != text:
            found.append(f"{path} is missing or stale")
    for path, (header, pixels) in outputs.images.items():
        problem = _image_problem(root, path, header, pixels)
        if problem:
            found.append(problem)
    found += [
        f"{path.relative_to(root)} is not a generated icon" for path in _stale_files(root, outputs)
    ]
    return found


def write(root: Path) -> list[str]:
    """Writes every output that changed and removes stale files (not an operating system's or
    an editor's clutter); says what it did, a line per file."""
    outputs = build(root)
    touched = []
    for path, text in outputs.texts.items():
        file = root / path
        if not file.is_file() or file.read_text(encoding="utf-8") != text:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(text, encoding="utf-8")
            touched.append(f"wrote {path}")
    # A PNG that already holds this image is left alone, however it was filtered and compressed.
    for path, (header, pixels) in outputs.images.items():
        file = root / path
        if _image_problem(root, path, header, pixels):
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_bytes(png_file(header, pixels))
            touched.append(f"wrote {path}")
    for stale in _stale_files(root, outputs):
        stale.unlink()
        touched.append(f"removed {stale.relative_to(root)}")
    return touched


def main(argv: list[str]) -> int:
    check = argv == ["--check"]
    if argv and not check:
        print("usage: tool/design/build_app_icons.py [--check]", file=sys.stderr)
        return 2
    try:
        if check:
            found = problems(ROOT)
            for problem in found:
                print(problem, file=sys.stderr)
            if found:
                print("Run `make app-icons` to rebuild the app icons.", file=sys.stderr)
                return 1
            return 0
        for line in write(ROOT):
            print(line)
    except (IconError, OSError, json.JSONDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
