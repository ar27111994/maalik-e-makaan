#!/usr/bin/env python3
"""Builds the app's icon font from design/icons/icons.json.

    python3 tool/design/build_icons.py           # subset the font and write the outputs
    python3 tool/design/build_icons.py --check   # verify the committed outputs match the icon set

Lucide (ISC licence) ships one font of about 1,700 glyphs; the app uses fewer than a
hundred. This subsets lucide-static's font (a pinned devDependency in package.json,
installed with `npm ci`) to exactly the glyphs the icon set names, so the app bundles
a few kilobytes instead of a megabyte, and generates `MmIcons` constants for it.

Outputs (all committed):
  packages/mm_ui/assets/fonts/MmIcons.ttf       the subset font
  packages/mm_ui/assets/fonts/LICENSE-lucide.txt Lucide's licence
  packages/mm_ui/lib/src/icons/mm_icons.g.dart  IconData constants
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ICON_SET = ROOT / "design" / "icons" / "icons.json"
LUCIDE = ROOT / "node_modules" / "lucide-static"
FONT_OUT = ROOT / "packages" / "mm_ui" / "assets" / "fonts" / "MmIcons.ttf"
LICENSE_OUT = ROOT / "packages" / "mm_ui" / "assets" / "fonts" / "LICENSE-lucide.txt"
DART_OUT = ROOT / "packages" / "mm_ui" / "lib" / "src" / "icons" / "mm_icons.g.dart"

FAMILY = "MmIcons"
IDENTIFIER = re.compile(r"^[a-z][A-Za-z0-9]*$")
DART_RESERVED = {"new", "default", "switch", "case", "class", "is", "in", "do", "if", "for", "var"}


class IconError(ValueError):
    """The icon set or the Lucide sources are unusable."""


def load_icon_set(path: Path | None = None) -> list[dict]:
    data = json.loads((path or ICON_SET).read_text(encoding="utf-8"))
    icons = data.get("icons")
    if not isinstance(icons, list) or not icons:
        raise IconError("icons.json must list icons")
    seen = set()
    for icon in icons:
        name = icon.get("name", "")
        if not IDENTIFIER.match(name) or name in DART_RESERVED:
            raise IconError(f"{name!r} is not a lowerCamelCase Dart identifier")
        if name in seen:
            raise IconError(f"duplicate icon name {name}")
        seen.add(name)
        if not isinstance(icon.get("lucide"), str):
            raise IconError(f"{name}: lucide glyph name missing")
        if not isinstance(icon.get("mirror", False), bool):
            raise IconError(f"{name}: mirror must be true or false")
    return icons


def lucide_codepoints(lucide: Path | None = None) -> dict[str, int]:
    info = json.loads(((lucide or LUCIDE) / "font" / "info.json").read_text(encoding="utf-8"))
    codepoints = {}
    for name, entry in info.items():
        code = entry["encodedCode"].lstrip("\\")
        codepoints[name] = int(code, 16)
    return codepoints


def lucide_version(lucide: Path | None = None) -> str:
    return json.loads(((lucide or LUCIDE) / "package.json").read_text(encoding="utf-8"))["version"]


def resolve(icons: list[dict], codepoints: dict[str, int]) -> list[tuple[str, str, int, bool]]:
    """(name, lucide glyph, code point, mirror) for every icon."""
    resolved = []
    for icon in icons:
        glyph = icon["lucide"]
        if glyph not in codepoints:
            raise IconError(f"{icon['name']}: Lucide has no glyph named {glyph}")
        resolved.append((icon["name"], glyph, codepoints[glyph], icon.get("mirror", False)))
    return resolved


def render_dart(resolved: list[tuple[str, str, int, bool]], version: str) -> str:
    out = [
        "// GENERATED by tool/design/build_icons.py from design/icons/icons.json",
        f"// (lucide-static {version}, ISC licence). Do not edit by hand: change the",
        "// icon set and run `make icons`.",
        "",
        "import 'package:flutter/widgets.dart';",
        "",
        "/// The app's icons: a subset of Lucide bundled as the MmIcons font.",
        "///",
        "/// Icons that point (back, forward, send, …) are mirrored in right-to-left",
        "/// layouts.",
        "abstract final class MmIcons {",
    ]
    for index, (name, glyph, code, mirror) in enumerate(resolved):
        if index > 0:
            out.append("")
        out += [
            f"  /// Lucide `{glyph}`{' (mirrored in right-to-left layouts)' if mirror else ''}.",
            f"  static const IconData {name} = IconData(",
            f"    0x{code:04x},",
            f"    fontFamily: '{FAMILY}',",
            "    fontPackage: 'mm_ui',",
        ]
        if mirror:
            out.append("    matchTextDirection: true,")
        out.append("  );")
    out += [
        "",
        "  /// Every icon by name, for the gallery and tests.",
        "  static const Map<String, IconData> all = {",
    ]
    out += [f"    '{name}': {name}," for name, _, _, _ in resolved]
    out += ["  };", "}", ""]
    return "\n".join(out)


def subset_font(source: Path, codepoints: list[int], target: Path) -> None:
    from fontTools import subset
    from fontTools.ttLib import TTFont

    font = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.hinting = False
    options.name_IDs = ["*"]
    options.notdef_outline = True
    options.glyph_names = False
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    place_glyphs(font)
    target.parent.mkdir(parents=True, exist_ok=True)
    font.save(target)


def place_glyphs(font) -> None:
    """Sets each glyph's left side bearing to where its outline starts.

    Lucide's font gives every glyph a left side bearing of 0 and a bounding
    box starting at 0, wherever its outline really starts, and the subsetter
    recalculates the box from the outline but keeps the bearing. TrueType
    rasterisers (FreeType, so Flutter on Android, Linux and the web) take the
    glyph's origin to be the box's start minus the bearing, so every icon was
    drawn against the left of its square: the three dots of `more` 10 dp left
    of centre at 24 dp. With the bearing equal to the outline's start, each
    glyph sits where Lucide drew it, centred in its square.
    """
    glyf = font["glyf"]
    hmtx = font["hmtx"]
    for name in font.getGlyphOrder():
        glyph = glyf[name]
        if glyph.numberOfContours == 0:
            continue
        glyph.recalcBounds(glyf)
        advance, _ = hmtx[name]
        hmtx[name] = (advance, glyph.xMin)


def misplaced_glyphs(path: Path) -> list[str]:
    """The glyphs of the font at [path] whose left side bearing is not where
    their outline starts, so a rasteriser would draw them off their place."""
    from fontTools.ttLib import TTFont

    font = TTFont(path, recalcTimestamp=False)
    glyf = font["glyf"]
    hmtx = font["hmtx"]
    misplaced = []
    for name in font.getGlyphOrder():
        glyph = glyf[name]
        if glyph.numberOfContours == 0:
            continue
        glyph.recalcBounds(glyf)
        if hmtx[name][1] != glyph.xMin:
            misplaced.append(name)
    return misplaced


def font_codepoints(path: Path) -> set[int]:
    from fontTools.ttLib import TTFont

    font = TTFont(path, recalcTimestamp=False)
    return set(font.getBestCmap())


def main(argv: list[str]) -> int:
    check = argv == ["--check"]
    if argv and not check:
        print("usage: tool/design/build_icons.py [--check]", file=sys.stderr)
        return 2
    try:
        if not (LUCIDE / "font" / "lucide.ttf").exists():
            raise IconError("node_modules/lucide-static is missing: run `npm ci`")
        resolved = resolve(load_icon_set(), lucide_codepoints())
        version = lucide_version()
    except (IconError, KeyError, json.JSONDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    dart = render_dart(resolved, version)
    license_text = (LUCIDE / "LICENSE").read_text(encoding="utf-8")
    wanted = {code for _, _, code, _ in resolved}
    if check:
        problems = []
        if not DART_OUT.exists() or DART_OUT.read_text(encoding="utf-8") != dart:
            problems.append(f"{DART_OUT.relative_to(ROOT)} is stale")
        if not FONT_OUT.exists() or font_codepoints(FONT_OUT) != wanted:
            problems.append(
                f"{FONT_OUT.relative_to(ROOT)} does not hold exactly the icon set's glyphs"
            )
        elif misplaced_glyphs(FONT_OUT):
            problems.append(
                f"{FONT_OUT.relative_to(ROOT)} has glyphs off their place (side bearings)"
            )
        if not LICENSE_OUT.exists() or LICENSE_OUT.read_text(encoding="utf-8") != license_text:
            problems.append(f"{LICENSE_OUT.relative_to(ROOT)} is missing or stale")
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            print("Run tool/design/build_icons.py to rebuild the icons.", file=sys.stderr)
            return 1
        return 0

    subset_font(LUCIDE / "font" / "lucide.ttf", sorted(wanted), FONT_OUT)
    LICENSE_OUT.write_text(license_text, encoding="utf-8")
    DART_OUT.parent.mkdir(parents=True, exist_ok=True)
    DART_OUT.write_text(dart, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
