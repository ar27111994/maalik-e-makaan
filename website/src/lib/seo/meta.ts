import { SITE } from "../../config/site.ts";
import { LOCALE_INFO, type Locale } from "../../i18n/locales.ts";

/** The site's name in `locale`. */
export function siteName(locale: Locale): string {
  return locale === "en" ? SITE.name : SITE.nameUrdu;
}

/**
 * The `<title>` of a page: the page's own title, then the site's name, unless
 * the title already starts with it (the home page's does).
 */
export function documentTitle(pageTitle: string, locale: Locale): string {
  const name = siteName(locale);
  return pageTitle.startsWith(name) ? pageTitle : `${pageTitle} | ${name}`;
}

export interface OgImage {
  /** Root-relative path of the 1200 × 630 PNG in public/og/. */
  readonly path: string;
  readonly width: 1200;
  readonly height: 630;
  readonly type: "image/png";
}

/** The site's Open Graph image for `locale` (generated by `npm run og`). */
export function ogImage(locale: Locale): OgImage {
  return { path: `/og/${locale}.png`, width: 1200, height: 630, type: "image/png" };
}

/** Open Graph locale values: the page's own, and the other language's. */
export function ogLocales(locale: Locale): { locale: string; alternate: string } {
  const other: Locale = locale === "en" ? "ur" : "en";
  return { locale: LOCALE_INFO[locale].ogLocale, alternate: LOCALE_INFO[other].ogLocale };
}
